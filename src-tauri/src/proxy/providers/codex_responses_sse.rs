//! Shared builders for the OpenAI Responses SSE envelope.
//!
//! The two Codex streaming converters — `streaming_codex_chat` (Chat Completions SSE →
//! Responses SSE) and `streaming_codex_anthropic` (Anthropic Messages SSE → Responses
//! SSE) — have completely different *input* state machines but must emit the identical
//! Responses event stream the Codex client understands. This module owns that output
//! envelope so the two converters cannot drift when an event's shape changes: a wire fix
//! lands here once instead of being mirrored in both files.
//!
//! Envelope builders take primitives or a caller-built `item` `Value`. Item shapes
//! that vary per converter (including function, namespace, custom, and tool-search
//! calls) are supplied through `output_item_added` / `output_item_done`. A shared,
//! bounded phase tracker adds Codex's commentary/final-answer distinction only to
//! streams generated by these converters.

use bytes::Bytes;
use futures::stream::{Stream, StreamExt};
use serde_json::{json, Value};
use std::collections::HashMap;

const COMMENTARY: &str = "commentary";
const FINAL_ANSWER: &str = "final_answer";
const MAX_PHASE_HELD_EVENTS: usize = 512;
const MAX_PHASE_HELD_BYTES: usize = 1024 * 1024;

/// A completed protocol envelope alone does not prove the model finished its
/// answer: tool calls, filtering, unknown stop reasons and a bare EOF must not
/// acquire final_answer. Keep this separate from the existing response status.
pub(crate) fn chat_final_answer_eligible(reason: Option<&str>) -> bool {
    matches!(reason, Some("stop"))
}

pub(crate) fn anthropic_final_answer_eligible(reason: Option<&str>) -> bool {
    matches!(reason, Some("end_turn" | "stop_sequence"))
}

fn assistant_message(item: &Value) -> bool {
    item.get("type").and_then(Value::as_str) == Some("message")
        && matches!(
            item.get("role").and_then(Value::as_str),
            None | Some("assistant")
        )
}

fn missing_phase(item: &Value) -> bool {
    match item.get("phase") {
        None | Some(Value::Null) => true,
        Some(Value::String(phase)) => phase.is_empty(),
        _ => false,
    }
}

fn refusal_message(item: &Value) -> bool {
    item.get("content")
        .and_then(Value::as_array)
        .is_some_and(|parts| {
            parts
                .iter()
                .any(|part| part.get("type").and_then(Value::as_str) == Some("refusal"))
        })
}

/// Give translated assistant messages the same phase Codex uses to fold progress
/// under its completed work. Reasoning after a message does not make it progress;
/// a later message/call does. A failed or incomplete turn has no inferred final
/// answer, and an upstream phase is always kept.
pub(crate) fn assign_message_phases(output: &mut [Value], completed: bool) {
    let last = output
        .iter()
        .rposition(|item| item.get("type").and_then(Value::as_str) != Some("reasoning"));
    let Some(last) = last else {
        return;
    };
    for (index, item) in output.iter_mut().enumerate() {
        if !assistant_message(item) || !missing_phase(item) {
            continue;
        }
        let phase = if index < last {
            COMMENTARY
        } else if completed && !refusal_message(item) {
            FINAL_ANSWER
        } else {
            continue;
        };
        item["phase"] = json!(phase);
    }
}

struct PendingMessage {
    output_index: u32,
    item: Value,
    event: Bytes,
}

/// Only message output_item.done waits for its phase. Text deltas are sent as
/// they arrive. This is applied to our translated streams, never official
/// Responses passthrough. Other items (including reasoning) may advance before
/// this item's done, just as parallel tool items do; their deltas/keepalives must
/// never wait for phase inference. If the pending message spans too many events
/// or bytes, it goes unphased in both its event and final output.
#[derive(Default)]
struct MessagePhases {
    pending: Option<PendingMessage>,
    held_events: usize,
    held_bytes: usize,
    last_non_reasoning: Option<u32>,
    settled: HashMap<String, Option<String>>,
}

impl MessagePhases {
    fn record(&mut self, item: &Value) {
        if let Some(id) = item.get("id").and_then(Value::as_str) {
            self.settled.insert(
                id.to_string(),
                item.get("phase")
                    .and_then(Value::as_str)
                    .map(str::to_string),
            );
        }
    }

    fn release(&mut self, phase: Option<&str>) -> Vec<Bytes> {
        let Some(mut pending) = self.pending.take() else {
            return Vec::new();
        };
        if let Some(phase) = phase.filter(|_| missing_phase(&pending.item)) {
            pending.item["phase"] = json!(phase);
            pending.event = output_item_done(pending.output_index, &pending.item);
        }
        self.record(&pending.item);
        self.held_events = 0;
        self.held_bytes = 0;
        vec![pending.event]
    }

    fn send_live(&mut self, event: Bytes) -> Vec<Bytes> {
        let mut out = Vec::new();
        if self.pending.is_some() {
            self.held_events = self.held_events.saturating_add(1);
            self.held_bytes = self.held_bytes.saturating_add(event.len());
            if self.held_events > MAX_PHASE_HELD_EVENTS || self.held_bytes > MAX_PHASE_HELD_BYTES {
                out.extend(self.release(None));
            }
        }
        out.push(event);
        out
    }

    fn keep_settled_phases(&self, output: &mut [Value]) {
        for item in output {
            if !assistant_message(item) {
                continue;
            }
            let Some(phase) = item
                .get("id")
                .and_then(Value::as_str)
                .and_then(|id| self.settled.get(id))
            else {
                continue;
            };
            if let Some(phase) = phase {
                item["phase"] = json!(phase);
            } else if let Some(item) = item.as_object_mut() {
                item.remove("phase");
            }
        }
    }

    fn push(&mut self, event: Bytes, final_answer_eligible: bool) -> Vec<Bytes> {
        // All events here come from sse_event, with one complete JSON data line.
        // Most are deltas and need no second JSON parse.
        let relevant = event.starts_with(b"event: response.output_item.")
            || event.starts_with(b"event: response.completed\n")
            || event.starts_with(b"event: response.incomplete\n")
            || event.starts_with(b"event: response.failed\n");
        if !relevant {
            return self.send_live(event);
        }
        let value = std::str::from_utf8(&event).ok().and_then(|text| {
            text.lines()
                .find_map(|line| line.strip_prefix("data: "))
                .and_then(|data| serde_json::from_str::<Value>(data).ok())
        });
        let Some(mut value) = value else {
            return self.send_live(event);
        };
        let event_type = value["type"].as_str().unwrap_or("").to_string();
        if matches!(
            event_type.as_str(),
            "response.completed" | "response.incomplete" | "response.failed"
        ) {
            let completed = event_type == "response.completed"
                && value["response"]["status"] == "completed"
                && final_answer_eligible;
            if let Some(output) = value["response"]["output"].as_array_mut() {
                assign_message_phases(output, completed);
                self.keep_settled_phases(output);
            }
            let phase = self.pending.as_ref().and_then(|pending| {
                let id = pending.item.get("id")?.as_str()?;
                value["response"]["output"]
                    .as_array()?
                    .iter()
                    .find(|item| {
                        assistant_message(item)
                            && item.get("id").and_then(Value::as_str) == Some(id)
                    })?
                    .get("phase")?
                    .as_str()
                    .map(str::to_string)
            });
            let mut out = self.release(phase.as_deref());
            if let Some(output) = value["response"]["output"].as_array_mut() {
                self.keep_settled_phases(output);
            }
            out.push(sse_event(&event_type, value));
            return out;
        }

        let index = value.get("output_index").and_then(Value::as_u64);
        let index = index.and_then(|index| u32::try_from(index).ok());
        let mut out = Vec::new();
        if let Some(index) = index.filter(|_| value["item"]["type"] != "reasoning") {
            self.last_non_reasoning = Some(
                self.last_non_reasoning
                    .map_or(index, |last| last.max(index)),
            );
            if self
                .pending
                .as_ref()
                .is_some_and(|pending| index > pending.output_index)
            {
                out.extend(self.release(Some(COMMENTARY)));
            }
        }
        if event_type == "response.output_item.done" && assistant_message(&value["item"]) {
            if let Some(index) = index.filter(|_| {
                missing_phase(&value["item"])
                    && value["item"].get("id").and_then(Value::as_str).is_some()
            }) {
                if self.last_non_reasoning.is_some_and(|last| index < last) {
                    value["item"]["phase"] = json!(COMMENTARY);
                    self.record(&value["item"]);
                    out.push(sse_event(&event_type, value));
                    return out;
                }
                // Duplicate closure events cannot safely acquire different phases.
                if self.pending.is_some() {
                    out.extend(self.release(None));
                    self.record(&value["item"]);
                    out.push(event);
                    return out;
                }
                self.held_events = 1;
                self.held_bytes = event.len();
                self.pending = Some(PendingMessage {
                    output_index: index,
                    item: value["item"].clone(),
                    event,
                });
                if self.held_bytes > MAX_PHASE_HELD_BYTES {
                    out.extend(self.release(None));
                }
                return out;
            } else {
                self.record(&value["item"]);
            }
        }
        out.extend(self.send_live(event));
        out
    }
}

/// Add message phases to a complete set of events generated from a JSON reply.
pub(crate) fn with_message_phases(
    events: impl IntoIterator<Item = Bytes>,
    final_answer_eligible: bool,
) -> Vec<Bytes> {
    let mut phases = MessagePhases::default();
    let mut out = Vec::new();
    for event in events {
        out.extend(phases.push(event, final_answer_eligible));
    }
    out.extend(phases.release(None));
    out
}

/// Add phases without buffering text deltas or changing source cancellation.
/// The bool travels only inside the converter: its protocol stop reason allows
/// a final answer. It is never serialized into the Responses wire format.
pub(crate) fn stream_with_message_phases(
    stream: impl Stream<Item = Result<(Bytes, bool), std::io::Error>> + Send + 'static,
) -> impl Stream<Item = Result<Bytes, std::io::Error>> + Send {
    async_stream::stream! {
        let mut phases = MessagePhases::default();
        futures::pin_mut!(stream);
        while let Some(event) = stream.next().await {
            match event {
                Ok((event, final_answer_eligible)) => {
                    for event in phases.push(event, final_answer_eligible) {
                        yield Ok(event);
                    }
                }
                Err(error) => {
                    for event in phases.release(None) {
                        yield Ok(event);
                    }
                    yield Err(error);
                    return;
                }
            }
        }
        for event in phases.release(None) {
            yield Ok(event);
        }
    }
}

/// Serialize one Responses SSE event with the standard `event:`/`data:` framing.
pub(crate) fn sse_event(event: &str, data: Value) -> Bytes {
    Bytes::from(format!(
        "event: {event}\ndata: {}\n\n",
        serde_json::to_string(&data).unwrap_or_default()
    ))
}

